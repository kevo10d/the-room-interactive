const storyEl = document.getElementById("story");
const choicesEl = document.getElementById("choices");
const kickerEl = document.getElementById("kicker");
const noteEl = document.getElementById("note");
const progressEl = document.getElementById("progress");
const safeBtn = document.getElementById("safeBtn");
const restartBtn = document.getElementById("restartBtn");

let seen = [];

function render(id) {
  const scene = scenes[id];
  if (!scene) return;
  seen.push(id);
  if (seen.length > 40) seen = seen.slice(-40);
  localStorage.setItem("theRoomScene", id);
  localStorage.setItem("theRoomSeen", JSON.stringify(seen));
  kickerEl.textContent = scene.kicker;
  storyEl.textContent = scene.text;
  choicesEl.innerHTML = "";
  scene.choices.forEach((c, i) => {
    const b = document.createElement("button");
    b.type = "button";
    b.innerHTML = "<span>Choice " + (i + 1) + "</span>" + c.label;
    b.addEventListener("click", () => {
      if (c.next === "static" || c.next === "sit" || c.next === "all_loops") {
        if (!document.body.classList.contains("safe")) document.body.classList.add("static-on");
      } else {
        document.body.classList.remove("static-on");
      }
      render(c.next);
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
    choicesEl.appendChild(b);
  });
  progressEl.textContent = "Passages this session: " + seen.length + " • now: " + id;
  noteEl.textContent = "Aimee is camera-only. Seizure-safe disables the static overlay.";
}

safeBtn.addEventListener("click", () => {
  const on = document.body.classList.toggle("safe");
  safeBtn.setAttribute("aria-pressed", on ? "true" : "false");
  if (on) document.body.classList.remove("static-on");
  localStorage.setItem("theRoomSafe", on ? "1" : "0");
});

restartBtn.addEventListener("click", () => {
  seen = [];
  document.body.classList.remove("static-on");
  render("start");
});

if (localStorage.getItem("theRoomSafe") === "1") {
  document.body.classList.add("safe");
  safeBtn.setAttribute("aria-pressed", "true");
}

const saved = localStorage.getItem("theRoomScene");
render(scenes[saved] ? saved : "start");
